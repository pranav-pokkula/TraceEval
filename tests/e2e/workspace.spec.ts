import { test, expect } from "@playwright/test";
import { mkdir, readFile } from "node:fs/promises";
const screenshots = process.env.BASE_URL ? "artifacts/production/screenshots" : "public/screenshots";
test("full fixture journey: evaluate, inspect, review, export, reload, compare", async ({ page }) => {
  const errors: string[] = []; page.on("pageerror", e => errors.push(e.message));
  await mkdir(screenshots, { recursive: true });
  await page.goto("/"); await expect(page.getByRole("heading", { name: "Evaluation overview" })).toBeVisible();
  await page.getByRole("button", { name: "New evaluation" }).first().click();
  await page.getByLabel("Run name").fill("Faithful fixture · full suite");
  await page.getByRole("button", { name: "Run evaluation", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Faithful fixture · full suite" })).toBeVisible();
  await expect(page.getByText("500/500", { exact: true }).first()).toBeVisible();
  await page.getByLabel("Support score").selectOption("2");
  await page.getByLabel("Review rationale").fill("The current fictional operating note explicitly states the seat capacity.");
  await page.getByRole("button", { name: "Save human review" }).click();
  await expect(page.getByText("Human review saved.")).toBeVisible();
  const downloadPromise = page.waitForEvent("download"); await page.getByRole("button", { name: "Export run" }).click(); const download = await downloadPromise; expect(download.suggestedFilename()).toMatch(/^traceeval-.*\.json$/);
  const exported = JSON.parse(await readFile((await download.path())!, "utf8"));
  expect(exported.run.results).toHaveLength(500); expect(exported.reviews).toHaveLength(1); expect(exported.reviews[0].source).toBe("human");
  await page.reload(); await expect(page.getByLabel("Support score")).toHaveValue("2");
  await page.getByRole("link", { name: "Overview", exact: true }).click();
  await page.getByRole("button", { name: "New evaluation" }).first().click();
  await page.getByLabel("Run name").fill("Injected faults · full suite"); await page.getByRole("combobox", { name: "Adapter", exact: true }).selectOption("perturbed");
  await page.getByRole("button", { name: "Run evaluation", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Injected faults · full suite" })).toBeVisible();
  await expect(page.getByText("document is not in this case's evidence.", { exact: false })).toBeVisible();
  await page.screenshot({ path: `${screenshots}/trace-inspector-desktop.png`, fullPage: true });
  await page.getByRole("link", { name: "Overview", exact: true }).click();
  await expect(page.getByText("100/500", { exact: true })).toBeVisible();
  await page.screenshot({ path: `${screenshots}/dashboard-desktop.png`, fullPage: true });
  await page.getByRole("link", { name: "Compare runs", exact: true }).click();
  await page.getByLabel("Baseline run").selectOption({ label: "Faithful fixture · full suite · fixture" });
  await page.getByLabel("Candidate run").selectOption({ label: "Injected faults · full suite · perturbed" });
  await expect(page.getByText("400", { exact: true })).toBeVisible();
  await page.screenshot({ path: `${screenshots}/comparison-desktop.png`, fullPage: true });
  expect(errors).toEqual([]);
});
